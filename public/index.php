<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| Production Error Handling
|--------------------------------------------------------------------------
*/

ini_set('display_errors', '0');
ini_set('display_startup_errors', '0');
ini_set('log_errors', '1');

error_reporting(E_ALL);

/*
|--------------------------------------------------------------------------
| Composer Autoloader
|--------------------------------------------------------------------------
*/

require_once __DIR__.'/../vendor/autoload.php';

use App\Router\Router;

/*
|--------------------------------------------------------------------------
| Canonical Domain
|--------------------------------------------------------------------------
*/

$canonicalDomain = 'sushilkumar.onrender.com';

/*
|--------------------------------------------------------------------------
| Current Host
|--------------------------------------------------------------------------
*/

$currentHost = strtolower($_SERVER['HTTP_HOST'] ?? '');

// Remove port from HTTP_HOST if present
$currentHost = preg_replace('/:\d+$/', '', $currentHost);

/*
|--------------------------------------------------------------------------
| HTTPS Detection
|--------------------------------------------------------------------------
|
| Render runs behind a reverse proxy, so X-Forwarded-Proto
| is checked as well.
|
*/

$isHttps =
    (! empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
    || (($_SERVER['SERVER_PORT'] ?? null) === '443')
    || (strtolower($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https');

/*
|--------------------------------------------------------------------------
| Request URI
|--------------------------------------------------------------------------
*/

$requestUri = $_SERVER['REQUEST_URI'] ?? '/';

/*
|--------------------------------------------------------------------------
| Canonical HTTPS Redirect
|--------------------------------------------------------------------------
*/

if ($currentHost !== $canonicalDomain || ! $isHttps) {
    header(
        'Location: https://'.$canonicalDomain.$requestUri,
        true,
        301
    );

    exit;
}

/*
|--------------------------------------------------------------------------
| Application
|--------------------------------------------------------------------------
*/

try {

    $router = new Router;

    /*
    |--------------------------------------------------------------------------
    | Web Routes
    |--------------------------------------------------------------------------
    */

    require_once __DIR__.'/../routes/web.php';

    /*
    |--------------------------------------------------------------------------
    | Dispatch Request
    |--------------------------------------------------------------------------
    */

    $router->dispatch();

} catch (Throwable $e) {

    /*
    |--------------------------------------------------------------------------
    | Log Error
    |--------------------------------------------------------------------------
    */

    error_log((string) $e);

    /*
    |--------------------------------------------------------------------------
    | Generic Production Response
    |--------------------------------------------------------------------------
    */

    http_response_code(500);

    echo 'Internal Server Error';
}
